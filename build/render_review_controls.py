"""Render manuscript exhibits directly from the recorded review experiments."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'paper/new_paper/figures'
DATA = ROOT / 'results/method_review'
NAMES = ('70/46.67/29.17/29.17 ACO', '43.75/43.75/43.75/43.75 ACO')
INPUTS = {}


def read(path):
    path = Path(path)
    INPUTS[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
    return json.loads(path.read_text())


def pct(value):
    return f'{100 * value:.2f}'


def table(file, caption, label, columns, header, rows, note):
    text = ('% Generated by build/render_review_controls.py\n'
            '\\begin{table}[htbp]\\centering\\small\n'
            f'\\caption{{{caption}}}\\label{{{label}}}\n'
            f'\\begin{{tabular}}{{{columns}}}\\toprule\n'
            + header + ' \\\\\n\\midrule\n'
            + '\n'.join(' & '.join(row) + ' \\\\' for row in rows)
            + '\n\\bottomrule\\end{tabular}\n'
            '\\par\\smallskip\\begin{minipage}{0.96\\textwidth}\\footnotesize\n'
            + note + '\n\\end{minipage}\\end{table}\n')
    (DEST / file).write_text(text)


def results(path):
    data = read(path)
    assert data['runs'] == 10000 and data['seed'] == 20260827
    return data, {x['strategy']: x for x in data['results']}


def main():
    _, base = results(ROOT / 'results/main_ladders_n10000.json')
    rows = []
    for path in [None, *sorted((DATA / 'mf_return_haircuts').glob('*.json'))]:
        data, out = ({'trend_haircut': 0}, base) if path is None else results(path)
        row = [str(round(data['trend_haircut'] * 10000))]
        for name in NAMES:
            row += [pct(out[name][k]) for k in ('equivalent_savings_rate', 'ruin_probability')]
        rows.append(row)
    table('review_mf.tex', 'Annual managed-futures return deductions at 175\\% exposure',
          'tab:review-mf', 'rrrrr',
          'Deduction (bp) & Prop. saving & Prop. ruin & Equal saving & Equal ruin', rows,
          'Saving and ruin in percent. Each deduction is applied after baseline MF fees and '
          'turnover costs, on every resident-year, without rescaling fluctuations. '
          '10,000 paired paths per specification; unlevered ACO has 10\\% saving and '
          '6.98\\% ruin throughout. These are annual return stress tests, not proportional '
          'reductions in an estimated risk premium.')

    rows = []
    for path in [None, *sorted((DATA / 'costs_175').glob('*.json'))]:
        data, out = ({'spread': .003, 'fx_hedge_cost': .001}, base) if path is None else results(path)
        row = [str(round(data['spread'] * 10000)), str(round(data['fx_hedge_cost'] * 10000))]
        for name in NAMES:
            row += [pct(out[name][k]) for k in ('equivalent_savings_rate', 'ruin_probability')]
        rows.append(row)
    table('review_costs.tex', 'Financing and hedge-cost stress at 175\\% exposure',
          'tab:review-costs', 'rrrrrr',
          'Spread (bp) & Hedge (bp) & Prop. saving & Prop. ruin & Equal saving & Equal ruin',
          rows, 'Saving and ruin in percent; 10,000 paired paths per row. The spread is '
          'additional to the resident bill return and applies to 75\\% of capital. '
          'Hedge friction applies to covered sleeve notionals. Unlevered ACO is '
          'unaffected by these charges and retains 10\\% saving and 6.98\\% ruin. '
          'The grid brackets crossings; no interpolated break-even estimate is reported.')

    data, out = results(DATA / 'post1970_ablation/ablation_1970_n10000.json')
    assert data['period'] == '1970-2025'
    rows = []
    for name, item in out.items():
        short = name.replace('Proportional four-sleeve, 175%', 'Proportional').replace(
            'Equal-weight four-sleeve, 175%', 'Equal weight').replace('without global bonds',
            'without bonds').replace('without managed futures', 'without MF').replace('%', '\\%')
        rows.append([short, *[pct(item[k]) for k in (
            'annual_volatility', 'equivalent_savings_rate', 'ruin_probability')]])
    table('review_post1970.tex', 'Complete and ablated 175\\% portfolios, 1970--2025',
          'tab:review-post1970', 'lrrr', 'Portfolio & Volatility & Saving & Ruin', rows,
          'All numbers in percent; 10,000 paired paths, 894 resident country-years, '
          'fixed-notional hedges and baseline costs. Removing a sleeve reallocates its '
          'weight pro rata at unchanged gross exposure. Ruin rates of 0.03\\% and '
          '0.04\\% correspond to three and four paths; their difference alone does '
          'not establish a ranking. The ACO utility target is recomputed on this window.')

    rows = []
    for length in (5, 10, 20):
        data = read(DATA / 'historical_panel_bootstrap' /
                    f'calendar_blocks_{length}y_outer100_inner1000.json')
        for name, short in zip(NAMES, ('Proportional', 'Equal weight')):
            s = data['summary'][name]
            dr = s['ruin_difference_vs_aco']
            saving = s['equivalent_savings_rate']
            rows.append([str(length), short,
                         f"{pct(dr['median'])} [{pct(dr['p05'])}, {pct(dr['p95'])}]",
                         f"{pct(saving['median'])} [{pct(saving['p05'])}, {pct(saving['p95'])}]",
                         str(round(100 * dr['share_better_than_aco']))])
    table('review_history.tex', 'Variation across resampled calendar histories at 175\\% exposure',
          'tab:review-history', 'rlrrr',
          'Block & Family & $\\Delta$ruin (pp) & Saving (\\%) & Lower ruin (\\%)', rows,
          'Median [5th, 95th percentile] across 100 outer histories per block length; '
          '1,000 paired inner lifecycle paths per history. Negative differences favor '
          'diversification. Lower ruin is the fraction of simulated histories with '
          'a negative estimated difference, not a posterior probability. Ranges '
          'include residual inner Monte Carlo noise and are not calibrated confidence intervals.')
    data = read(DATA / 'common_consumption_target/aco_common_target_n10000.json')
    rows = []
    for name, short in zip(data['strategies'], ('ACO', 'ACO 175\\%', 'Proportional 175\\%', 'Equal 175\\%')):
        item = data['strategies'][name]
        rates = item['implicit_withdrawal_rate_positive_capital']
        rows.append([short, pct(item['shortfall_probability_all_paths']),
                     pct(item['shortfall_probability']), pct(rates['median']),
                     pct(rates['p90']), pct(item['mean_shortfall_share'])])
    table('review_common.tex', 'Common ACO planned income and implied withdrawal rates',
          'tab:review-common', 'lrrrrr',
          'Portfolio & Fail, all & Fail, retired & Median draw & P90 draw & Mean deficit',
          rows, 'All entries in percent. All-path failures use 10,000 lifetimes; '
          'retired failures, initial draws and mean deficit use 9,832 eligible paths. '
          'Draw is the target divided by own initial retirement capital. Mean deficit '
          'is the mean path-level share of cumulative planned financial withdrawals '
          'left unfunded, including zero for successful paths. Public pensions are '
          'common across strategies and excluded from this financial-deficit measure.')
    (DATA / 'review_exhibits_provenance.json').write_text(json.dumps({
        'renderer': str(Path(__file__).relative_to(ROOT)),
        'renderer_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'inputs_sha256': INPUTS,
    }, indent=2) + '\n')


if __name__ == '__main__':
    main()
